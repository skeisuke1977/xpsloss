class FollowupTests(unittest.TestCase):
    def test_dense_al_every_loss_both_tails(self):
        path = Path(__file__).resolve().parents[1] / "benchmarks/inputs/al_elfdb_v1.0.bulk.json"
        osc, = load_config(path).material.oscillators
        expected = np.array(AL_KK)
        losses = np.arange(0.5, 150, 0.5)
        for i, step in enumerate((0.1, 0.05)):
            nodes = np.round(np.arange(0., 150 + step/2, step), 10)
            level = (osc.strength_eV2 * osc.width_eV * nodes /
                     ((osc.energy_eV**2 - nodes**2)**2 + (osc.width_eV * nodes)**2))
            for j, tail in enumerate(("hard_cut", "power_law_3")):
                with self.subTest(step=step, tail=tail):
                    ref = expected[:, 2*i+j]
                    actual = tabulated_elf_kk(nodes, level, losses, low_energy="zero", high_energy=tail)
                    self.assertTrue(np.all(abs(actual.real_negative_inverse_epsilon - ref)
                                           <= np.maximum(1e-9, 1e-7*abs(ref))))

    def test_gapped_sum_at_nested_tolerances(self):
        cases = ((STATIC, 7.89193759455495, 0, 0, -0.11194158142913157),
                 (STATIC, 7.89193759455495, 3, 0, -0.05206757592461837),
                 (NEAR, 5.846831168012581, 5.887660937002207, 0, 10.492078770914003),
                 (BROAD, 1.550890771276142, 0, 0.9009708343237725, -0.014411633365118389),
                 (SCAN_28, 0.6671472392854397, 0.67, 0.5, 5.182863781548754))
        for rows, gap, t, q, ref in cases:
            mat = Material("synthetic", gap, tuple(Oscillator(*o) for o in rows))
            for epsabs, epsrel in ((1e-7, 1e-7), (1e-9, 1e-7), (1e-12, 1e-10)):
                with self.subTest(gap=gap, t=t, epsabs=epsabs, epsrel=epsrel):
                    f = negative_inverse_dielectric_function(mat, t, q, epsabs=epsabs, epsrel=epsrel)
                    self.assertLessEqual(abs(f.real - ref), max(epsabs, epsrel * abs(ref)))

    def test_static_point_in_epsilon_and_diagnostics(self):
        mat = Material("synthetic", 7.89193759455495, tuple(Oscillator(*o) for o in STATIC))
        ref = -0.11194158142913157
        diag = dielectric_diagnostics(mat)
        self.assertEqual(diag.static_status, "stable")
        self.assertAlmostEqual(diag.static_negative_inverse_epsilon, ref, delta=1e-7*abs(ref))
        r = dielectric_response(mat, [0, 3])
        self.assertAlmostEqual(r.negative_inverse_epsilon[0].real, ref, delta=1e-7*abs(ref))
        self.assertLessEqual(r.real_quadrature_error[0], 1e-7*abs(ref))

    def test_dispersed_resonance_component_accuracy(self):
        line = Oscillator(4.017220767437674, 2.497700902738755, 9.185425063805724e-8, 0.03712174177269153)
        t, q = 4.02099068386561, 0.16326392005751011
        for gap, ref in ((0., -0.9547319417533154), (1., -0.9547319417403913)):
            with self.subTest(gap=gap):
                f = dielectric_response(Material("synthetic", gap, (line,)), t, q).negative_inverse_epsilon
                self.assertAlmostEqual(f.real, ref, delta=1e-7*abs(ref))
                self.assertAlmostEqual(f.imag, 6762512.882427565, delta=1e-7*6762512.882427565)

    def test_initial_panel_limit_is_input_error(self):
        for limit in (1, 2):
            with self.subTest(limit=limit):
                with self.assertRaisesRegex(ValueError, "too small"):
                    negative_inverse_dielectric_function(Material("synthetic", 14, (Oscillator(15, 180, 2),)),
                                                         20, limit=limit)
                with self.assertRaisesRegex(ValueError, "too small"):
                    effective_cross_section_fixed_depth(Material("synthetic", 0, (Oscillator(15, 180, 2, .5),)),
                                                         1000, 20, 10, epsilon_momentum="k_total", limit=limit)

    def test_gapped_sum_exceeds_binary64_range(self):
        mat = Material("synthetic", 0.001, (Oscillator(1, 5e307, 0.02),) * 5)
        # At T=0 the sum of five finite positive contributions exceeds binary64.
        with self.assertRaisesRegex(NumericalConvergenceError, r"gapped KK oscillator sum.*loss_eV=0, index=\(1,\)"):
            negative_inverse_dielectric_function(mat, [10., 0.])

    def test_overflow_reports_only_offending_loss_and_index(self):
        mat = Material("synthetic", 0, (Oscillator(15, 1e300, 1e-300),))
        for func in (loss_function, negative_inverse_dielectric_function):
            with self.subTest(func=func.__name__), self.assertRaises(NumericalConvergenceError) as ctx:
                func(mat, [5., 15., 22.])
            self.assertIn("loss_eV=15", str(ctx.exception))
            self.assertIn("index=(1,)", str(ctx.exception))
            self.assertNotIn("22", str(ctx.exception))


